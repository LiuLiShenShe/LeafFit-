# -*- coding: utf-8 -*-
"""Task5R Phase 5 — label-free identity separability gate (R0-R6).

For every near-contact leaf pair in benchmark_manifest.json:
  * build kNN candidate edges among the union of the TWO proposed leaf
    components ONLY (candidate selection uses geometry alone, never the
    labels being tested — labels enter only POST-HOC to name an edge
    within/cross);
  * compute G6/G7 identity features from the CORRECTED occlusion-aware
    real-observation signature (core.observation_identity);
  * score each edge under frozen ablations:
      R0  euclidean distance control (expect NO separation)
      R1  c_vis   (visibility Jaccard)
      R2  c_app   (appearance cosine, real RGB)
      R3  c_occ   (occlusion/depth-order consistency)
      R4  c_mv    (0.4 c_vis + 0.3 c_app + 0.3 c_occ)
      R5  surface coherence (local-PCA normal alignment) only
      R6  c_mv AND surface coherence combined score
  * within-edge := both endpoints in the SAME proposed leaf; cross-edge :=
    endpoints in DIFFERENT leaves of the pair; stem/background edges are not
    generated by construction (components exclude stem-like points).

Metrics per pair and aggregated: counts, median/IQR within vs cross, AUROC
(within = positive class), AUPRC + prevalence + lift, bootstrap 95% CI,
Cliff's delta effect size, dev vs held-out split reported separately.
Dev plants may choose thresholds; held-out is evaluated ONCE, frozen.
"""
