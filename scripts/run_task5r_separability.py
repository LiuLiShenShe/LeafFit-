REPO_DEFAULT = _SCRIPT.parent.parent
for p in (str(REPO_DEFAULT), str(REPO_DEFAULT / "core")):
    if p not in sys.path:
        sys.path.insert(0, p)

from core.observation_identity import git_commit  # noqa: E402
